"""
Test case: Default packaging configuration and behavior

This test verifies that poexy-core correctly handles projects with minimal or
default packaging configuration. Default behavior should work for standard
Python packages without requiring extensive configuration.

Test scenario:
- A project uses default packaging configuration with minimal setup
- The project contains standard Python package structure
- The build system applies default settings for package creation
- Standard source packaging should work without explicit configuration

Expected behavior:
- Default source packaging creates properly structured wheel and sdist packages
- Python source files are correctly included in package distributions
- Package installation works correctly with default settings
- No binary executables are created for default source-only packages

Edge case significance:
This tests default packaging behavior which is essential for user experience.
Good defaults reduce configuration overhead and make packaging accessible for
simple projects while ensuring consistent behavior across different setups.
"""

from pathlib import Path

import pytest
from assertpy import assert_that

from tests.conftests.paths import SamplePaths
from tests.utils.venv import TestVirtualEnvironment

# pylint: disable=redefined-outer-name


@pytest.fixture()
def project_path(sample_project):
    return sample_project(SamplePaths.CoreFunctionality / "default")


def test_wheel(
    project,
    project_path,
    assert_wheel_build,
    wheel_data_purelib_folder,
    default_python_tag,
    dist_package_name,
    package_name,
    venv: TestVirtualEnvironment,
):
    with project(project_path):
        assert_zip_file = assert_wheel_build(project_path)
        assert_zip_file(
            [
                wheel_data_purelib_folder(default_python_tag)
                / dist_package_name()
                / "__init__.py"
            ],
            strict=True,
        )
        purelib_path = venv.site_package / dist_package_name() / "__init__.py"
        assert_that(purelib_path.exists()).is_true()
        binary_path = venv.bin_path / package_name()
        assert_that(binary_path.exists()).is_false()


def test_sdist(
    project,
    project_path,
    assert_sdist_build,
    dist_package_name,
    package_name,
    venv: TestVirtualEnvironment,
):
    with project(project_path):
        assert_tar_file = assert_sdist_build(project_path)
        assert_tar_file(
            [
                Path("default") / "__init__.py",
            ],
            strict=True,
        )
        purelib_path = venv.site_package / dist_package_name() / "__init__.py"
        assert_that(purelib_path.exists()).is_true()
        binary_path = venv.bin_path / package_name()
        assert_that(binary_path.exists()).is_false()
